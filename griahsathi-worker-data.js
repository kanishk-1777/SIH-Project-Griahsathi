// LOCAL STORAGE HELPERS
// ============================================================

function gsRead(key, fallback = null) {

    try {

        const value = localStorage.getItem(key);

        return value === null
            ? fallback
            : JSON.parse(value);

    } catch (error) {

        console.warn(
            'Griahsathi storage read failed:',
            key,
            error
        );

        return fallback;
    }
}


function gsWrite(key, value) {

    try {

        localStorage.setItem(
            key,
            JSON.stringify(value)
        );

        return true;

    } catch (error) {

        console.warn(
            'Griahsathi storage write failed:',
            key,
            error
        );

        return false;
    }
}


