function gsSlug(value) {

    return String(value || '')
        .toLowerCase()
        .trim()
        .replace(/&/g, 'and')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '');
}


// ============================================================
// AGE CALCULATOR
// ============================================================

function gsAge(dob) {

    const birth = new Date(
        dob + 'T00:00:00'
    );

    if (Number.isNaN(birth.getTime())) {

        return 0;
    }

    const today = new Date();

    let age =
        today.getFullYear() -
        birth.getFullYear();

    const month =
        today.getMonth() -
        birth.getMonth();

    if (
        month < 0 ||
        (
            month === 0 &&
            today.getDate() < birth.getDate()
        )
    ) {

        age--;
    }

    return age;
}


