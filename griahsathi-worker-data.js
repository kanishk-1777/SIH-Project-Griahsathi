function gsTheme() {

    const light =
        localStorage.getItem(
            'griahsathi-theme'
        ) === 'light';

    document.body.classList.toggle(
        'light-mode',
        light
    );

    const desktop =
        document.getElementById(
            'themeToggle'
        );

    const mobile =
        document.getElementById(
            'mobileThemeToggle'
        );

    if (desktop) {

        desktop.textContent =
            light
                ? '🌙'
                : '☀️';
    }

    if (mobile) {

        mobile.textContent =
            light
                ? '🌙 Dark Mode'
                : '☀️ Light Mode';
    }
}


// ============================================================
// THEME + MOBILE MENU SETUP
// ============================================================

function gsSetupTheme(
    menuId = 'mobileMenu'
) {

    const menu =
        document.getElementById(
            menuId
        );

    const button =
        document.getElementById(
            'menuButton'
        );

    if (
        button &&
        menu
    ) {

        button.addEventListener(
            'click',
            () => {
                menu.classList.toggle(
                    'hidden'
                );
            }
        );
    }

    const toggles = [
        document.getElementById(
            'themeToggle'
        ),
        document.getElementById(
            'mobileThemeToggle'
        )
    ].filter(Boolean);


    toggles.forEach(
        btn => {

            btn.addEventListener(
                'click',
                () => {

                    localStorage.setItem(
                        'griahsathi-theme',
                        document.body.classList.contains(
                            'light-mode'
                        )
                            ? 'dark'
                            : 'light'
                    );

                    gsTheme();
                }
            );
        }
    );


    gsTheme();
}