  adult(dob) {

    const d =
      new Date(dob);


    if (
      Number.isNaN(
        d.getTime()
      )
    ) {
      return false;
    }


    const now =
      new Date();


    let age =
      now.getFullYear() -
      d.getFullYear();


    const m =
      now.getMonth() -
      d.getMonth();


    if (
      m < 0 ||
      (
        m === 0 &&
        now.getDate() <
          d.getDate()
      )
    ) {

      age--;
    }


    return age >= 18;
  },


