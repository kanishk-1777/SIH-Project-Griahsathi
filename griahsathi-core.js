  avgRating(worker) {

    const rs =
      worker.reviews || [];


    if (!rs.length) {
      return 0;
    }


    return (
      rs.reduce(
        (
          sum,
          r
        ) =>
          sum +
          Number(
            r.rating || 0
          ),
        0
      ) / rs.length
    );
  },


