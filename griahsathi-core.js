  bindNav() {

    const navbar =
      document.getElementById(
        "gs-navbar"
      );


    if (!navbar) {
      return;
    }


    const currentPage =
      location.pathname
        .split("/")
        .pop() ||
      "index.html";


    navbar
      .querySelectorAll(
        "[data-nav-page]"
      )
      .forEach(link => {

        const page =
          link.getAttribute(
            "data-nav-page"
          );


        if (
          page === currentPage
        ) {

          link.classList.add(
            "active"
          );

        }

      });


    const mobileBtn =
      document.getElementById(
        "gs-mobile-btn"
      );


    const mobileMenu =
      document.getElementById(
        "gs-mobile-menu"
      );


    if (
      mobileBtn &&
      mobileMenu
    ) {

      mobileBtn.onclick = () => {

        const open =
          mobileMenu.classList.toggle(
            "open"
          );


        mobileBtn.setAttribute(
          "aria-expanded",
          String(open)
        );


        mobileBtn.textContent =
          open
            ? "✕"
            : "☰";
      };


      mobileMenu
        .querySelectorAll("a")
        .forEach(link => {

          link.addEventListener(
            "click",
            () => {

              mobileMenu.classList.remove(
                "open"
              );


              mobileBtn.setAttribute(
                "aria-expanded",
                "false"
              );


              mobileBtn.textContent =
                "☰";

            }
          );

        });

    }


    const themeButtons = [

      document.getElementById(
        "gs-theme-toggle"
      ),

      document.getElementById(
        "gs-mobile-theme"
      )

    ].filter(Boolean);


    const updateThemeButtons =
      () => {

        const theme =
          localStorage.getItem(
            this.keys.theme
          ) || "dark";


        themeButtons.forEach(
          button => {

            button.textContent =
              theme === "dark"
                ? "☀️"
                : "🌙";


            if (
              button.id ===
              "gs-mobile-theme"
            ) {

              button.textContent =
                theme === "dark"
                  ? "☀️  Light Mode"
                  : "🌙  Dark Mode";

            }

          }
        );

      };


    themeButtons.forEach(
      button => {

        button.onclick = () => {

          this.toggleTheme();

          updateThemeButtons();

        };

      }
    );


    this.applyTheme();

    updateThemeButtons();

  }

